def _extract_banks(t: str) -> list:
    """Какие банки упомянуты в описании (для матчинга связок). Уникальные имена."""
    low = t.lower()
    out: list = []
    for kw, name in _DESC_BANK_WORDS.items():
        if kw in low and name not in out:
            out.append(name)
    return out


def _ml_no_third(low: str) -> bool:
    """Запрет 3-х лиц на НЕ-русских языках (фолбэк к AI). По со-встречаемости."""
    # турецкий: «üçüncü şahıs(lardan) ... kabul etmiyorum / kabul edilmez»
    tr_third = any(k in low for k in (
        "üçüncü şah", "ucuncu sah", "3.şah", "3 şah", "3.sah", "3 sah",
        "üçüncü kiş", "ucuncu kis", "3. şah", "3. kiş"))
    tr_no = any(k in low for k in ("kabul etm", "kabul edilm", "kabul yok"))
    if tr_third and tr_no:
        return True
    # английский: «no third party / not accept third part / third party not accepted»
    if "third part" in low and any(k in low for k in (
            "no third", "not accept", "don't accept", "dont accept",
            "do not accept", "not accepted", "no 3rd", "without third")):
        return True
    # индонезийский / вьетнамский
    if "pihak ketiga" in low and ("tidak" in low or "tdk" in low or "bukan" in low):
        return True
    if ("bên thứ ba" in low or "ben thu ba" in low) and ("không" in low or "khong" in low):
        return True
    return False


def _payment_note_trap(low: str) -> bool:
    """Просят написать КОНКРЕТНУЮ фразу в НАЗНАЧЕНИИ/описании ПЛАТЕЖА — манипуляция
    для спора/чарджбэка. ВАЖНО: «оставьте комментарий/отзыв», «güzel yorum»,
    «write a nice comment» — это ПРОСЬБА ОБ ОТЗЫВЕ, не ловушка."""
    has_write = any(k in low for k in (
        "yazın", "yazınız", "yaziniz", "yazin", "напиш", "укаж",
        "write", "indicate", "state ", "put the note"))
    if not has_write:
        return False
    # TR: «(ödeme) açıklama kısmına ... yazın»
    if ("açıklama" in low or "aciklama" in low):
        return True
    # RU: «в назначении платежа …», «в комментарии К ПЛАТЕЖУ/ПЕРЕВОДУ …»
    if "назначен" in low and "платеж" in low:
        return True
    if "коммент" in low and any(k in low for k in ("к платеж", "к перевод", "к оплат")):
        return True
    # EN: «write ... in payment description/reference/note»
    if any(k in low for k in ("payment description", "payment reference", "payment note")):
        return True
    return False

# ── Вербовка / скам-схема в описании ─────────────────────────────────────────
# Мошенники вербуют людей прямо в описании объявления: обещают «лёгкие деньги»
# и уводят в личку (teleg:/@ник) мимо биржи. Помечаем такие красным флагом.
_SCAM_RECRUIT = re.compile(
    r'('
    r'руб\w*\s+капуст'                       # «рубим капусту»
    r'|капуст[ауыой]\b'                       # капуста = деньги (сленг)
    r'|%\s*(?:с|за)\s*круг'                   # «7% с круга»
    r'|(?:с|за)\s+круга?\b'                   # «с круга»
    r'|teleg\w*\s*[:\-–]'                     # «teleg: ник»
    r'|тг\s*[:\-–]\s*\S'                      # «тг: ник»
    r'|пиш\w*\s+(?:в\s+)?(?:тг|телег|лс|личк|вотсап|whats|вацап)'
    r'|(?:ищу|нужны|набор)\s+люд'             # «ищу людей / набор людей»
    r'|\bобуч\w+'                             # обучение / обучаю / обучу
    r'|науч\w+|наставник'                     # «научу», «наставник»
    r'|схем\w*\s+заработ'                     # «схема заработка»
    r'|за\s*работ\w*\s+\d+\s*%'               # «заработок 10%»
    r'|в\s+(?:тг|телег\w*|телеге|вотсап|whats|вацап|лс\b|личк\w+)'   # увод в личку/тг
    r'|связк\w*\s+без\s+(?:пластик|карт)'     # «связки без пластика»
    r'|без\s+пластик'                         # «без пластика» (= без карт, вербовка)
    r'|помож\w+\s+(?:\w+\s+)?обмен'           # «поможем совершить обмен» (посредник)
    r'|ответим\s+на\s+(?:ваши\s+)?вопрос'     # «ответим на ваши вопросы»
    r'|предостав\w+\s+(?:сразу\s+)?(?:номер|фио|реквизит|данные|снилс|паспорт)'  # выкачка данных
    r'|(?:скинь|пришли|укажи|дай|напиши)\s+(?:сразу\s+)?(?:фио|снилс|паспорт|номер\s+карт)'
    r'|@[a-zA-Z][\w]{3,}'                     # внешний @username в описании
    r')',
    re.IGNORECASE | re.UNICODE,
)

# Смешение латиницы и кириллицы в одном слове = техника обхода фильтров
# («Pyбuм кaпyсту» — P,y,u латинские). В нормальном объявлении не бывает.
_WORD = re.compile(r'[a-zA-Zа-яёА-ЯЁ]{3,}', re.UNICODE)
_LAT  = re.compile(r'[a-zA-Z]')
_CYR  = re.compile(r'[а-яёА-ЯЁ]', re.UNICODE)


def _has_mixed_script(text: str) -> bool:
    """True если есть слово с ≥2 латинских И ≥2 кириллических букв (гомоглиф-обход)."""
    for w in _WORD.findall(text):
        if len(_LAT.findall(w)) >= 2 and len(_CYR.findall(w)) >= 2:
            return True
    return False


def parse_description(text: str) -> dict:
    """
    Парсит описание P2P объявления.

    Возвращает:
    {
        'third_party': True | False | None,
        'exact_amount': int | None,
        'flags': ['✅ 3-е лица', '⚠️ ровно 5000₸', ...],
    }
    """
    if not text or not text.strip():
        return {"third_party": None, "exact_amount": None, "scam_recruit": False,
                "trap": False, "any_bank": False, "banks": [], "flags": []}

    t = text.strip()
    flags: list[str] = []

    # «принимаю с любого банка / любой картой» — банк-агностик. На практике это
    # же значит «приму от любого отправителя» → 3-и лица ок (если не запрещено).
    any_bank = bool(_ANY_BANK.search(t))

    # ── Третьи лица ───────────────────────────────────────────────────────────
    # ВАЖНО: приоритет у «НЕ принимает». YES-паттерн жадно ловит «принимаю от
    # третьих» даже во фразе «НЕ принимаю от третьих» — поэтому если сработал
    # запрет, считаем что 3-х лиц нет (консервативно, безопасно для фильтра).
    low_t   = t.lower()
    has_no  = bool(_NO_THIRD.search(t)) or _ml_no_third(low_t)   # +турецкий/англ./ЮВА
    has_yes = bool(_YES_THIRD.search(t))

    if has_no:
        third_party = False
        flags.append("❌ нет 3-х лиц")
    elif has_yes or any_bank:           # «любой банк/карта» → приём от 3-х лиц
        third_party = True
        flags.append("✅ 3-е лица ок")
    else:
        third_party = None   # не упомянуто

    # ── Точная сумма ──────────────────────────────────────────────────────────
    # Порог ≥100: «только 1 ПЛАТЕЖОМ» / «1 лицо» — это НЕ сумма, а кол-во.
    exact_amount: int | None = None
    m = _EXACT_AMOUNT.search(t)
    if m:
        try:
            val = int(m.group(1).replace(" ", ""))
            if val >= 100:
                exact_amount = val
                flags.append(f"⚠️ ровно {exact_amount:,}".replace(",", " "))
        except ValueError:
            pass

    # ── Временные ограничения ─────────────────────────────────────────────────
    if _TIME_LIMIT.search(t):
        flags.append("🕐 время ограничено")

    # ── ИП / юрлица ───────────────────────────────────────────────────────────
    if _NO_BUSINESS.search(t):
        flags.append("🏢 нет ИП/юрлиц")

    # ── Только конкретный банк ────────────────────────────────────────────────
    bm = _ONLY_BANK.search(t)
    if bm:
        flags.append(f"🏦 {bm.group(0)}")

    # ── Цена-приманка: «строго по заявке» / «без заявки другое объявление» ─────
    bait = bool(_BAIT_REQUEST.search(t))
    if bait:
        flags.insert(0, "📋 цена-приманка: только по заявке")

    # ── Просят написать фразу в назначении платежа (манипуляция для спора) ─────
    note_trap = _payment_note_trap(low_t)
    if note_trap:
        flags.insert(0, "⚠️ просят фразу в назначении платежа")

    # ── Ловушка для спора (сильный сигнал) ────────────────────────────────────
    trap = bool(_TRAP.search(t)) or bait or note_trap
    if _TRAP.search(t):
        flags.insert(0, "⚠️ СТРАННЫЕ УСЛОВИЯ — возможна ловушка")

    # ── Развод с отложенной оплатой ───────────────────────────────────────────
    defer_pay = bool(_DEFER_PAY.search(t))

    # ── Вербовка / скам ───────────────────────────────────────────────────────
    # Ловим по фразам, обходу фильтров (латиница+кириллица) и отложенной оплате
    scam_recruit = bool(_SCAM_RECRUIT.search(t)) or _has_mixed_script(t) or defer_pay
    if defer_pay:
        flags.insert(0, "🚩 ОПЛАТА ПОЗЖЕ / «ЗАВТРА» — РАЗВОД")
    elif scam_recruit:
        flags.insert(0, "🚩 ВЕРБОВКА / СКАМ")

    return {
        "third_party":  third_party,
        "exact_amount": exact_amount,
        "scam_recruit": scam_recruit,
        "trap":         trap,
        "any_bank":     any_bank,
        "banks":        _extract_banks(t),
        "flags":        flags,
    }


def flags_line(text: str) -> str:
    """Возвращает строку значков для вставки в карточку объявления."""
    info = parse_description(text)
    if not info["flags"]:
        return ""
    return "\n🏷 " + " · ".join(info["flags"])
