"""
Парсер описаний P2P объявлений.

Автоматически определяет:
• Принимает ли мерчант переводы от третьих лиц
• Требует ли точную сумму (несмотря на указанные лимиты)
• Временные ограничения работы
• Другие важные условия

Используется для значков в списке объявлений и умного фильтра.
"""
import re


# Третьи лица в любых формах и с опечатками: «третьих/третих/третьи лиц/лица»,
# «3 лиц», «3-х лиц», «3-ими лицами», «3их лиц» и т.п.
_THIRD = r'(?:трет\w*\s*лиц\w*|3[\s\-]?(?:ими|их|ми|х|и)?\s*лиц\w*|чужих|посторонних)'

# Отрицание принятия: «не приму/принимаю/принимаются», «не работаю», «нельзя»…
_NEG = r'(?:не\s+при[нм]\w*|не\s+работа\w*|нет\b|нельзя|запрещ)'

# ── Паттерны "НЕ принимает от третьих лиц" ───────────────────────────────────
_NO_THIRD = re.compile(
    r'('
    r'не\s+при[нм]\w*\s+(?:перевод\w*\s+)?(?:от\s+)?' + _THIRD +
    # _THIRD <разделители/«строго»> отрицание: «третьи лица - не принимаются»
    r'|' + _THIRD + r'[\s\-—:!,.]*(?:строго\s+)?' + _NEG +
    # «от 3 не принимаю», «от 3 лиц строго не принимаю» (3 без слова «лиц»)
    r'|(?:от\s+)?\b3\b\s+(?:лиц\w*\s+)?(?:строго\s+)?' + _NEG +
    r'|без\s+' + _THIRD +
    r'|не\s+от\s+треть\w+'
    # «только (с) свои/личные карт/счёт/счетов/деньги/реквизиты» — оплата строго
    # со своего счёта. «только с личных счетов ИЛИ доверенных лиц» = ограничение,
    # а НЕ «3 лица ок» (NEG имеет приоритет над «доверенными лицами»).
    r'|только\s+(?:с[о]?\s+)?(?:свои?\w*|личн\w+)\s+(?:перевод|карт|деньг|счет|счёт|реквизит)\w*'
    r'|оплат\w*\s+только\s+(?:с[о]?\s+)?(?:свои?\w*|личн\w+)'
    r'|перевод\w*\s+только\s+(?:со\s+свои|от\s+себ|личн)'
    r'|переводы?\s+только\s+с\s+(?:ваш|свои|личн)'   # «переводы только с ваших личных карт»
    r'|no\s+third\s+party|not\s+work\s+with\s+third'
    # «работаю строго с 1 лицами», «только первые лица», «1 лицо» = НЕ 3-и лица
    r'|(?:перв\w+|\b1)\s+лиц\w*'
    r'|строго\s+(?:с\s+)?(?:перв\w+|1)'
    # «только от 1 го», «от 1-го», «с 1 го лица», «только от первого» = первое лицо
    r'|(?:только\s+|строго\s+)?(?:от|с)\s+1\s*-?\s*го\b'
    r'|(?:только\s+|строго\s+)?(?:от|с)\s+перв\w+'
    r'|\b1\s*-?\s*го\s+лиц'
    r')',
    re.IGNORECASE | re.UNICODE,
)

# ── Паттерны "ПРИНИМАЕТ от третьих лиц" ──────────────────────────────────────
_YES_THIRD = re.compile(
    r'('
    r'при[нм]\w*\s+(?:от\s+)?' + _THIRD +
    r'|(?:от\s+)?' + _THIRD + r'\s*(?:при[нм]\w*|ок\b|ok\b|можно|допуска\w*|допустим|да\b)'
    r'|с\s+чужих\s+карт\w*\s*(?:принима|можно|ок|ok|да\b)'
    r'|чужие\s+(?:перевод\w*|карт\w*)\s*(?:принима|можно|ок)'
    r'|не\s+против\s+' + _THIRD +
    r'|third\s+party\s*(?:ok|accepted|yes)'
    # «доверенные лица», «дов лица», «родственники» = работает с 3-ми лицами
    r'|довер\w*\s+лиц\w*'
    r'|\bдов\.?\s*лиц\w*'
    r'|родственник\w*'
    r'|карт\w*\s+близк\w+'
    r')',
    re.IGNORECASE | re.UNICODE,
)

# ── Точная сумма ──────────────────────────────────────────────────────────────
_EXACT_AMOUNT = re.compile(
    r'(?:ровно|только|строго|точно)\s+(?:на\s+)?'
    r'([\d][\d\s]{0,9})'
    r'\s*(?:руб|₽|тенге|₸|kzt|rub|лир|tl|usd|\$)?',
    re.IGNORECASE | re.UNICODE,
)

# ── ЛОВУШКА для спора (сильный сигнал) ───────────────────────────────────────
# Заставляют написать фразу-«согласие» — скринят её и выигрывают апелляцию.
_TRAP = re.compile(
    r'('
    r'со\s+вс[ёе]м\s+соглас'                       # «со всем согласен» (скрипт-фраза)
    r'|пиш\w+[:\s«"]+[^"»\n]{0,40}соглас'           # «пишите: ... согласен»
    r'|напиш\w+\s+(?:фраз|следующ|это\b|мне\b)'     # «напишите фразу...»
    # контроль над отменой: «отмена ордера только по запросу / через фразу»
    r'|отмен\w*\s+(?:ордер\w*\s+)?(?:только\s+)?(?:по|через)\s+запрос'
    r'|отмен\w*\s+ордер\w*\s+(?:можно\s+)?(?:только\s+)?(?:напис|по\s+согл|с\s+согл)'
    r')',
    re.IGNORECASE | re.UNICODE,
)

# ── Просит чек/квитанцию (мягкий инфо-флаг, НЕ ловушка) ───────────────────────
_RECEIPT_REQ = re.compile(
    r'('
    r'чек\w*\s+(?:на\s+почт|от\s+(?:имени|лица)\s+банк)'   # «чек на почту / от лица банка»
    r'|скрин\w*\s+чек'                                     # «скрин чека»
    r'|квитанц\w+\s+(?:на\s+почт|пришл|вышл)'
    r')',
    re.IGNORECASE | re.UNICODE,
)

# ── Временные ограничения ─────────────────────────────────────────────────────
_TIME_LIMIT = re.compile(
    r'('
    r'с\s+\d+\s*(?:до|по)\s*\d+'
    r'|работаю?\s+(?:до|с)\s+\d+'
    r'|ночью\s+не\s+работ'
    r'|только\s+(?:днем|в\s+день)'
    r'|в\s+рабочее\s+время'
    r'|\d+:\d+\s*[-–—]\s*\d+:\d+'
    r')',
    re.IGNORECASE | re.UNICODE,
)

# ── Отложенная оплата = РАЗВОД ───────────────────────────────────────────────
# «оплачу завтра / позже», «сегодня выходной оплачу завтра» — разводят на то,
# чтобы ты отпустил USDT до оплаты. В P2P оплата ВСЕГДА сейчас.
_DEFER_PAY = re.compile(
    r'('
    r'оплат\w*\s+(?:будет\s+)?(?:завтра|позже|потом|поздн|не\s+сразу)'
    r'|оплачу\s+(?:завтра|позже|потом|поздн|вечером|ночью)'
    r'|заплачу\s+(?:завтра|позже|потом)'
    r'|переве?д\w*\s+(?:завтра|позже|потом|вечером)'
    r'|деньг\w*\s+(?:будут\s+|пришл\w+\s+)?(?:завтра|позже|потом)'
    r'|с?кин\w+\s+(?:сначала|перв\w+)'               # «кинь/скинь первым»
    r'|отпуст\w+\s+(?:сначала|перв\w+)'              # «отпусти первым»
    r')',
    re.IGNORECASE | re.UNICODE,
)

# ── Принимает с ЛЮБОГО банка ─────────────────────────────────────────────────
# «переводите с любого банка», «любая карта» — банк-агностик, можно связать
# с любой второй ногой (общий банк не требуется).
_ANY_BANK = re.compile(
    r'('
    r'любо\w*\s+банк'                         # любой/любого банка
    r'|с\s+любо\w*\s+(?:банк|карт)'           # с любого банка / с любой карты
    r'|любо\w*\s+карт'                        # любая карта / любой картой
    r'|не\s*важно\s+(?:какой\s+|с\s+какого\s+)?банк'  # не важно какой банк
    r'|все\s+банк'                            # все банки
    r'|any\s+bank'
    r')',
    re.IGNORECASE | re.UNICODE,
)

# ── Запрет ИП / юрлиц ────────────────────────────────────────────────────────
_NO_BUSINESS = re.compile(
    r'('
    r'(?:ип|юрлиц|юр\.\s*лиц|самозанят|бизнес)\s+(?:не\s+принима|нет|нельзя)'
    r'|не\s+принима\w+\s+(?:ип|юрлиц)'
    r')',
    re.IGNORECASE | re.UNICODE,
)

# ── Требует СБП / конкретный банк ────────────────────────────────────────────
_ONLY_BANK = re.compile(
    r'только\s+(?:сбер|тинькофф|тинк|сбербанк|альфа|втб|райффайзен|казком|халык|банк)',
    re.IGNORECASE | re.UNICODE,
)

# ── Вербовка / скам-схема в описании ─────────────────────────────────────────
# Мошенники вербуют людей прямо в описании объявления: обещают «лёгкие деньги»
# и уводят в личку (teleg:/@ник) мимо биржи. Помечаем такие красным флагом.
_SCAM_RECRUIT = re.compile(
    r'('
    r'руб\w*\s+капуст'                       # «рубим капусту»
    r'|капуст[ауыой]\b'                       # капуста = деньги (сленг)
    r'|%\s*(?:с|за)\s*круг'                   # «7% с круга»
    r'|(?:с|за)\s+круга?\b'                   # «с круга»
    r'|teleg\w*\s*[:\-–]'                     # «teleg: ник»
    r'|тг\s*[:\-–]\s*\S'                      # «тг: ник»
    r'|пиш\w*\s+(?:в\s+)?(?:тг|телег|лс|личк|вотсап|whats|вацап)'
    r'|(?:ищу|нужны|набор)\s+люд'             # «ищу людей / набор людей»
    r'|\bобуч\w+'                             # обучение / обучаю / обучу
    r'|науч\w+|наставник'                     # «научу», «наставник»
    r'|схем\w*\s+заработ'                     # «схема заработка»
    r'|за\s*работ\w*\s+\d+\s*%'               # «заработок 10%»
    r'|в\s+(?:тг|телег\w*|телеге|вотсап|whats|вацап|лс\b|личк\w+)'   # увод в личку/тг
    r'|связк\w*\s+без\s+(?:пластик|карт)'     # «связки без пластика»
    r'|без\s+пластик'                         # «без пластика» (= без карт, вербовка)
    r'|помож\w+\s+(?:\w+\s+)?обмен'           # «поможем совершить обмен» (посредник)
    r'|ответим\s+на\s+(?:ваши\s+)?вопрос'     # «ответим на ваши вопросы»
    r'|предостав\w+\s+(?:сразу\s+)?(?:номер|фио|реквизит|данные|снилс|паспорт)'  # выкачка данных
    r'|(?:скинь|пришли|укажи|дай|напиши)\s+(?:сразу\s+)?(?:фио|снилс|паспорт|номер\s+карт)'
    r'|@[a-zA-Z][\w]{3,}'                     # внешний @username в описании
    r')',
    re.IGNORECASE | re.UNICODE,
)

# Смешение латиницы и кириллицы в одном слове = техника обхода фильтров
# («Pyбuм кaпyсту» — P,y,u латинские). В нормальном объявлении не бывает.
_WORD = re.compile(r'[a-zA-Zа-яёА-ЯЁ]{3,}', re.UNICODE)
_LAT  = re.compile(r'[a-zA-Z]')
_CYR  = re.compile(r'[а-яёА-ЯЁ]', re.UNICODE)


def _has_mixed_script(text: str) -> bool:
    """True если есть слово с ≥2 латинских И ≥2 кириллических букв (гомоглиф-обход)."""
    for w in _WORD.findall(text):
        if len(_LAT.findall(w)) >= 2 and len(_CYR.findall(w)) >= 2:
            return True
    return False


def parse_description(text: str) -> dict:
    """
    Парсит описание P2P объявления.

    Возвращает:
    {
        'third_party': True | False | None,
        'exact_amount': int | None,
        'flags': ['✅ 3-е лица', '⚠️ ровно 5000₸', ...],
    }
    """
    if not text or not text.strip():
        return {"third_party": None, "exact_amount": None,
                "scam_recruit": False, "trap": False, "any_bank": False, "flags": []}

    t = text.strip()
    flags: list[str] = []

    # «принимаю с любого банка / любой картой» — банк-агностик. На практике это
    # же значит «приму от любого отправителя» → 3-и лица ок (если не запрещено).
    any_bank = bool(_ANY_BANK.search(t))

    # ── Третьи лица ───────────────────────────────────────────────────────────
    # ВАЖНО: приоритет у «НЕ принимает». YES-паттерн жадно ловит «принимаю от
    # третьих» даже во фразе «НЕ принимаю от третьих» — поэтому если сработал
    # запрет, считаем что 3-х лиц нет (консервативно, безопасно для фильтра).
    has_no  = bool(_NO_THIRD.search(t))
    has_yes = bool(_YES_THIRD.search(t))

    if has_no:
        third_party = False
        flags.append("❌ нет 3-х лиц")
    elif has_yes or any_bank:           # «любой банк/карта» → приём от 3-х лиц
        third_party = True
        flags.append("✅ 3-е лица ок")
    else:
        third_party = None   # не упомянуто

    # ── Точная сумма ──────────────────────────────────────────────────────────
    # Порог ≥100: «только 1 ПЛАТЕЖОМ» / «1 лицо» — это НЕ сумма, а кол-во.
    exact_amount: int | None = None
    m = _EXACT_AMOUNT.search(t)
    if m:
        try:
            val = int(m.group(1).replace(" ", ""))
            if val >= 100:
                exact_amount = val
                flags.append(f"⚠️ ровно {exact_amount:,}".replace(",", " "))
        except ValueError:
            pass

    # ── Временные ограничения ─────────────────────────────────────────────────
    if _TIME_LIMIT.search(t):
        flags.append("🕐 время ограничено")

    # ── ИП / юрлица ───────────────────────────────────────────────────────────
    if _NO_BUSINESS.search(t):
        flags.append("🏢 нет ИП/юрлиц")

    # ── Только конкретный банк ────────────────────────────────────────────────
    bm = _ONLY_BANK.search(t)
    if bm:
        flags.append(f"🏦 {bm.group(0)}")

    # ── Ловушка для спора (сильный сигнал) ────────────────────────────────────
    trap = bool(_TRAP.search(t))
    if trap:
        flags.insert(0, "⚠️ СТРАННЫЕ УСЛОВИЯ — возможна ловушка")
    # Просит чек/квитанцию — мягкий инфо-флаг (не ловушка)
    if _RECEIPT_REQ.search(t):
        flags.append("📧 просит чек — проверь поступление денег сам")

    # ── Развод с отложенной оплатой ───────────────────────────────────────────
    defer_pay = bool(_DEFER_PAY.search(t))

    # ── Вербовка / скам ───────────────────────────────────────────────────────
    # Ловим по фразам, обходу фильтров (латиница+кириллица) и отложенной оплате
    scam_recruit = bool(_SCAM_RECRUIT.search(t)) or _has_mixed_script(t) or defer_pay
    if defer_pay:
        flags.insert(0, "🚩 ОПЛАТА ПОЗЖЕ / «ЗАВТРА» — РАЗВОД")
    elif scam_recruit:
        flags.insert(0, "🚩 ВЕРБОВКА / СКАМ")

    return {
        "third_party":  third_party,
        "exact_amount": exact_amount,
        "scam_recruit": scam_recruit,
        "trap":         trap,
        "any_bank":     any_bank,
        "flags":        flags,
    }


def flags_line(text: str) -> str:
    """Возвращает строку значков для вставки в карточку объявления."""
    info = parse_description(text)
    if not info["flags"]:
        return ""
    return "\n🏷 " + " · ".join(info["flags"])
