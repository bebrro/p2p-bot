"""
Парсер описаний P2P объявлений.

Автоматически определяет:
• Принимает ли мерчант переводы от третьих лиц
• Требует ли точную сумму (несмотря на указанные лимиты)
• Временные ограничения работы
• Другие важные условия

Используется для значков в списке объявлений и умного фильтра.
"""
import re


# Третьи лица в любых формах: «третьих/третьи/третье лиц/лица/лицами»,
# «3 лиц», «3-х лиц» и т.п.
_THIRD = r'(?:треть\w+\s+лиц\w*|3[\-хx]*\s*лиц\w*|чужих|посторонних)'

# ── Паттерны "НЕ принимает от третьих лиц" ───────────────────────────────────
_NO_THIRD = re.compile(
    r'('
    r'не\s+принима\w*\s+(?:перевод\w*\s+)?(?:от\s+)?' + _THIRD +
    r'|' + _THIRD + r'\s+(?:не\s+принима|нет|нельзя|запрещ|не\s+работа)'
    r'|без\s+' + _THIRD +
    r'|не\s+от\s+треть\w+'
    r'|только\s+(?:свои?\w*|личн\w+)\s+(?:перевод|карт|деньг)\w*'
    r'|перевод\w*\s+только\s+(?:со\s+свои|от\s+себ|личн)'
    r'|no\s+third\s+party'
    # «работаю строго с 1 лицами», «только первые лица», «1 лицо» = НЕ 3-и лица
    r'|(?:перв\w+|\b1)\s+лиц\w*'
    r'|строго\s+(?:с\s+)?(?:перв\w+|1)'
    r')',
    re.IGNORECASE | re.UNICODE,
)

# ── Паттерны "ПРИНИМАЕТ от третьих лиц" ──────────────────────────────────────
_YES_THIRD = re.compile(
    r'('
    r'принима\w*\s+(?:от\s+)?' + _THIRD +
    r'|(?:от\s+)?' + _THIRD + r'\s*(?:принима\w*|ок\b|ok\b|можно|допуска\w*|допустим|да\b)'
    r'|с\s+чужих\s+карт\w*\s*(?:принима|можно|ок|ok|да\b)'
    r'|чужие\s+(?:перевод\w*|карт\w*)\s*(?:принима|можно|ок)'
    r'|не\s+против\s+' + _THIRD +
    r'|third\s+party\s*(?:ok|accepted|yes)'
    r')',
    re.IGNORECASE | re.UNICODE,
)

# ── Точная сумма ──────────────────────────────────────────────────────────────
_EXACT_AMOUNT = re.compile(
    r'(?:ровно|только|строго|точно)\s+(?:на\s+)?'
    r'([\d][\d\s]{0,9})'
    r'\s*(?:руб|₽|тенге|₸|kzt|rub|лир|tl|usd|\$)?',
    re.IGNORECASE | re.UNICODE,
)

# ── Временные ограничения ─────────────────────────────────────────────────────
_TIME_LIMIT = re.compile(
    r'('
    r'с\s+\d+\s*(?:до|по)\s*\d+'
    r'|работаю?\s+(?:до|с)\s+\d+'
    r'|ночью\s+не\s+работ'
    r'|только\s+(?:днем|в\s+день)'
    r'|в\s+рабочее\s+время'
    r'|\d+:\d+\s*[-–—]\s*\d+:\d+'
    r')',
    re.IGNORECASE | re.UNICODE,
)

# ── Запрет ИП / юрлиц ────────────────────────────────────────────────────────
_NO_BUSINESS = re.compile(
    r'('
    r'(?:ип|юрлиц|юр\.\s*лиц|самозанят|бизнес)\s+(?:не\s+принима|нет|нельзя)'
    r'|не\s+принима\w+\s+(?:ип|юрлиц)'
    r')',
    re.IGNORECASE | re.UNICODE,
)

# ── Требует СБП / конкретный банк ────────────────────────────────────────────
_ONLY_BANK = re.compile(
    r'только\s+(?:сбер|тинькофф|тинк|сбербанк|альфа|втб|райффайзен|казком|халык|банк)',
    re.IGNORECASE | re.UNICODE,
)


def parse_description(text: str) -> dict:
    """
    Парсит описание P2P объявления.

    Возвращает:
    {
        'third_party': True | False | None,
        'exact_amount': int | None,
        'flags': ['✅ 3-е лица', '⚠️ ровно 5000₸', ...],
    }
    """
    if not text or not text.strip():
        return {"third_party": None, "exact_amount": None, "flags": []}

    t = text.strip()
    flags: list[str] = []

    # ── Третьи лица ───────────────────────────────────────────────────────────
    # ВАЖНО: приоритет у «НЕ принимает». YES-паттерн жадно ловит «принимаю от
    # третьих» даже во фразе «НЕ принимаю от третьих» — поэтому если сработал
    # запрет, считаем что 3-х лиц нет (консервативно, безопасно для фильтра).
    has_no  = bool(_NO_THIRD.search(t))
    has_yes = bool(_YES_THIRD.search(t))

    if has_no:
        third_party = False
        flags.append("❌ нет 3-х лиц")
    elif has_yes:
        third_party = True
        flags.append("✅ 3-е лица ок")
    else:
        third_party = None   # не упомянуто

    # ── Точная сумма ──────────────────────────────────────────────────────────
    exact_amount: int | None = None
    m = _EXACT_AMOUNT.search(t)
    if m:
        try:
            exact_amount = int(m.group(1).replace(" ", ""))
            flags.append(f"⚠️ ровно {exact_amount:,}".replace(",", " "))
        except ValueError:
            pass

    # ── Временные ограничения ─────────────────────────────────────────────────
    if _TIME_LIMIT.search(t):
        flags.append("🕐 время ограничено")

    # ── ИП / юрлица ───────────────────────────────────────────────────────────
    if _NO_BUSINESS.search(t):
        flags.append("🏢 нет ИП/юрлиц")

    # ── Только конкретный банк ────────────────────────────────────────────────
    bm = _ONLY_BANK.search(t)
    if bm:
        flags.append(f"🏦 {bm.group(0)}")

    return {
        "third_party":  third_party,
        "exact_amount": exact_amount,
        "flags":        flags,
    }


def flags_line(text: str) -> str:
    """Возвращает строку значков для вставки в карточку объявления."""
    info = parse_description(text)
    if not info["flags"]:
        return ""
    return "\n🏷 " + " · ".join(info["flags"])
